/**
 * fall_alarm.h - 「疑似摔倒」事件链的唯一入口（检测器报一次，后面全自动）
 *
 * 这条链做什么（用户原话整理）：
 *   检测到异常 -> 判断疑似摔倒 -> 手机收到「疑似摔倒」
 *     -> 板子弹窗「您摔到了吗？」（有 / 没有）+ 语音问同一句话
 *     -> 用户点按钮 或 说话回答（先到的那个算数）
 *     -> 答「没有」：撤弹窗 + 停响铃 + 手机收到「已取消」
 *        答「有」/ 超时没回应：手机收到「机主摔倒！」+ 板子响铃 + 红色报警页
 *
 * ★ 本文件**只声明入口，不做摔倒判定**（判定方式还没定：本地模型 / 启发式 /
 *   云端，由队友给）。将来检测器不论在哪一侧（hello_app 的 ai_sound_detect、
 *   本地小模型、MQTT 下发的云端判断），只要在任务上下文里调一次
 *   fall_alarm_trigger("检测到摔倒") 这条链就会自己跑完。
 *
 * 实现：app/robot_ui/main.c 的「疑似摔倒事件链」一节（那边才够得着音频设备、
 *       界面、报警页、推送那几套现成部件）。本头文件**自给自足**：只依赖
 *       <stdint.h>，不引 LVGL、不引 robot_ui 的任何头 —— 因为 hello_app 也要
 *       include 它（跨 app 直调，单一大镜像里符号最终链接时解析，和
 *       robot_ui_bridge.h 是同一个做法），而 hello_app 的编译命令里没有
 *       LVGL 的头文件路径。
 *
 * 线程约定（调用方必须守）：
 *   1) **任何任务线程都能调**：入口内部只做幂等判重 + 起一条工作线程，立刻返回
 *      （TTS 合成、ASR 识别、放音与开麦都是阻塞的，全在那条工作线程里）；
 *   2) **不许在中断/音频回调里调**：内部要 malloc + pthread_create；
 *   3) robot_ui 还没起来时也能调（界面那几步在 robot_ui_bridge 那道闸门后面
 *      安全空转，报警/响铃/推送照常）。
 */

#ifndef FALL_ALARM_H
#define FALL_ALARM_H

#include <stdint.h>

/****************************************************************************
 * 问的那句话（屏幕上显示的和 TTS 念的必须是同一句，所以只在这里留一份）
 ****************************************************************************/

#define FALL_ALARM_QUESTION   "您摔到了吗？"

/****************************************************************************
 * 等回答的超时（毫秒）—— 可配置，编译时改这个宏即可
 *
 * 为什么默认 25 秒（用户给的范围是 20~30 秒）：
 *   - 这条链上"问"这一步本身就要占掉几秒：云端 TTS 合成（几百 ms 到几秒）
 *     + 把这句话放完（约 2 秒）。**这个超时是从"开始听"起算的**，不含上面那段，
 *     所以真正留给老人的是完整的 25 秒；
 *   - 下限不能再短：摔倒之后的老人可能躺在地上，起身、回神、开口都要时间，
 *     20 秒已经是最紧的（再短就是把"还没来得及回答"误判成报警）；
 *   - 上限不能再长：超时等于按最坏情况处理（发正式报警 + 响铃），家属收到
 *     "机主摔倒"到能赶到现场之间，每一秒都在等这个判定，25 秒已经是"还能忍受"
 *     的量级（用户第一轮会先看到手机上的「疑似摔倒」推送，不至于毫无准备）；
 *   - 这个数还会显示在弹窗状态行上（"请回答「有」或「没有」（25 秒内）"），
 *     改宏的时候界面上跟着变，不用两处一起改。
 ****************************************************************************/

#ifndef FALL_ALARM_ANSWER_TIMEOUT_MS
#  define FALL_ALARM_ANSWER_TIMEOUT_MS   (25 * 1000)
#endif

/****************************************************************************
 * Public Types
 ****************************************************************************/

/* 这条链现在走到哪了（只读快照，给日志/诊断用）。
 * IDLE 是"没有在跑"；跑完之后**保留最后的结果**（ALARMED / CANCELLED）直到
 * 下一次触发 —— 这样触发方过一会儿再问一次还能知道这条链最后怎么收的。 */
typedef enum
{
  FALL_ALARM_IDLE = 0,     /* 没在跑 */
  FALL_ALARM_ASKING,       /* 正在问 / 正在等回答 */
  FALL_ALARM_ALARMED,      /* 已按"有"（或超时没回应）进入正式报警 */
  FALL_ALARM_CANCELLED     /* 已按"没有"取消警报 */
} fall_alarm_state_t;

/* fall_alarm_trigger() 的返回值 */
#define FALL_ALARM_TRIGGER_OK      0   /* 已受理，链条开始跑 */
#define FALL_ALARM_TRIGGER_BUSY    1   /* 上一条还在跑，本次触发被忽略（会打一行日志） */
#define FALL_ALARM_TRIGGER_ERROR  (-1) /* 内存不够 / 工作线程起不来，本次没跑起来 */

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/**
 * @brief  报一次「疑似摔倒」，跑完整条事件链（唯一的入口）
 *
 * @param  source  谁报的，进日志用（"sound_detect" / "local_model" / "mqtt_test"…）。
 *                 允许 NULL（按空串处理）。
 * @return 见上面三个 FALL_ALARM_TRIGGER_* 的说明
 *
 * 幂等：上一条链还在跑时重复调用**不做任何事**（不打第二遍弹窗、不发第二条报警），
 * 只打一行 `[Fall] 已在处理中，忽略本次触发` 日志并返回 BUSY。
 */
int fall_alarm_trigger(const char *source);

/**
 * @brief  这条链此刻的状态（任何线程可读的只读快照）
 */
fall_alarm_state_t fall_alarm_get_state(void);

#endif /* FALL_ALARM_H */
