/****************************************************************************
 * app/hello_app/kws_dtw.h
 *
 * 唤醒词模块 —— 纯本地「命令词识别」（MFCC + DTW）
 * 智爱陪伴 - AI老人陪伴守护终端
 *
 * 目标词：「你好，openvela」/「Hello，openvela」
 *   两个语种变体各占一个模板槽（slot 0 / slot 1），命中任意一条都算唤醒。
 *
 * 这个模块**纯计算**：不开麦、不起线程、不碰 LVGL、不持有任何设备。
 * 父 agent（当时的麦克风持有者）在录音回调里把 PCM 喂给 kws_feed()，
 * 返回 1 就是"刚匹配到唤醒词"。半双工铁律由此天然成立：
 * 本模块从不碰 AUDIOIOC_*，麦克风只有一个持有者 —— 录音那个线程。
 *
 * ============================================================================
 * 算法一条线（全部自己实现，不引入任何外部依赖、不用 CMSIS-DSP）
 * ============================================================================
 *
 *   PCM(16k/单声道/s16le)
 *    → 预加重 0.97 + 汉明窗，20ms 窗 / 10ms 跳（320 / 160 采样）
 *    → 512 点复数 FFT（320 点补零，radix-2，自己写的蝶形）
 *    → 功率谱（257 个 bin）
 *    → 26 个 Mel 三角滤波器（0..8000Hz），取 ln
 *    → 13 维特征 = [0] 帧对数能量 dBFS（×0.5 权重）
 *                  [1..12] log-mel 的 DCT-II 系数（标准 MFCC）
 *    → 定点 int16（Q6，×64）
 *    → 匹配用特征点 2:1 抽取（一个特征点 = 20ms 音频）
 *    → 能量端点检测（自适应本底 + 绝对地板，双条件）+ 掐头去尾
 *    → 倒谱均值归一 CMN（每维减均值 → 去信道/音量/麦克风增益）
 *    → 与每条模板做 Sakoe-Chiba 带宽限制的 DTW，取最小距离
 *    → 最小距离 ≤ 阈值 → 命中，kws_feed() 返回 1
 *
 * ----------------------------------------------------------------------------
 * 为什么是「整句匹配」而不是「只匹配后半段 openvela」
 * ----------------------------------------------------------------------------
 *   1) 两段式短语的两个语种变体（"你好，openvela" / "Hello，openvela"）
 *      天然就是**两条模板**，多模板 DTW 取最小值即可 —— 不需要任何
 *      "找后半段从哪开始"的定位逻辑，少一个能出错的环节。
 *   2) 端点检测给出的本来就是整句边界；DTW 的单调对齐本来就吸收语速差
 *      （"你好"说得快一点/慢一点、中间停多久都能对上）。
 *   3) 整句打分**区分度更高**：只说 "openvela" 不带称呼语时，前半段对不上，
 *      距离会明显偏大 —— 减少"电视里念到 openvela 就唤醒"这类误唤醒。
 *   4) 代价：模板长一倍、DTW 慢一倍（见下面的量化数字），
 *      对"几秒一次、一次几毫秒"的负载完全可以接受。
 *   想改成"只匹配后半段"不需要改代码：把 slot 2/3 录成只念 "openvela" 的
 *   模板即可（多模板取最小值，谁近算谁），但那样就会丢掉第 3 条的区分度。
 *
 * ============================================================================
 * 量化数字（都是按本文件里的常量算出来的，改常量要一起改这里）
 * ============================================================================
 *
 * 【模板】
 *   每条模板 = 最多 KWS_MAX_FEAT(100) 个特征点 × 13 维 × 2 字节 = 2600 字节
 *   RAM（定长数组，没录满的部分留空）。
 *   一条 1.3 秒的短语实际只有 65 个特征点 = 1690 字节有效数据，
 *   落盘文件 = 24 字节头 + 1690 = 1714 字节 ≈ 1.7 KiB/条。
 *   4 条模板 RAM 合计 10400 字节。
 *
 * 【常驻 RAM（静态 .bss，不含调用方喂进来的 PCM）】
 *   模板 4×2600 = 10400
 *   待判句子缓冲 100×13×2 + 100×2(dB) = 2800
 *   预滚环 10×13×2 = 260，输入拼帧缓冲 320×2 = 640
 *   FFT 工作区 re/im 512×4×2 = 4096，旋转因子 256×4×2 = 2048，
 *     位反转表 512×2 = 1024
 *   功率谱 257×4 = 1028，mel/dct/窗表 ≈ 3350，DTW 两行 2×101×4 = 808
 *   自检用暂存 100×13×2 = 2600
 *   合计 ≈ 27 KiB（其中模板 10.2 KiB 是可调的：KWS_MAX_TEMPLATES /
 *   KWS_MAX_FEAT 都是宏，砍到 2 条模板就是 16.8 KiB）。
 *   栈：kws_feed 路径 < 256 字节；kws_selftest < 1.5 KiB（可以随时调，
 *   它不动流式状态）。
 *
 * 【每帧浮点运算量（10ms 一帧，帧长 20ms）】
 *   乘法：预加重 320 + 窗 320 + 功率谱 514 + mel 组 512 + DCT 312 + 定点 13
 *         + FFT 蝶形 2304×4 = 9216   → 合计 ≈ 1.12 万次乘法
 *   加法：FFT 蝶形 2304×6 = 13824 + 功率谱 257 + mel 512 + DCT 312
 *         + 帧能量 320                → 合计 ≈ 1.52 万次加法
 *   两者合计 ≈ 2.6 万次浮点运算，FFT 占约 87%。
 *   DTW 每格 13 次乘法。格子数不是 qn×tn，是带宽内的那一条带：
 *     模板/句子都 62 点（1.24 秒）→ r = 18，带内共 1952 格 ≈ 2.5 万次乘
 *     都 100 点（2.0 秒，最坏）→ r = 26，≈ 4600 格 ≈ 6.0 万次乘
 *
 * 【Cortex-M33 @240MHz + 单精度 FPU（-mfpu=fpv5-sp-d16，无 DSP/SIMD）
 *   —— 下面全是估算，不是实测（kws_selftest 会在板子上打实测值）】
 *   240MHz 来自 vendor/sifli/boards/sf32lb52/sf32lb52_devkit_lcd/src/bsp_init.c
 *   的 HAL_RCC_HCPU_ConfigHCLK(240)。
 *   一个 10ms 帧的 MFCC ≈ 6.5 万周期 → **≈ 270 微秒/帧 → 约 2.7% CPU**
 *   （浮动范围大概 200~350 微秒：新雅 libm 的 logf/log10f 是纯 float 实现
 *    ef_*，不落软 double，这一点是估算的关键前提）。
 *   一次 DTW（62 点模板、1952 格 × 约 65 周期）≈ 13 万周期
 *   → **≈ 0.53 毫秒/模板**；最坏情况（各自 100 点、约 4600 格）
 *   ≈ 30 万周期 ≈ 1.25 毫秒/模板，4 条模板一次判定最坏 ≈ 5 毫秒。
 *   → DTW 只在"一句话说完 + 尾静音超时"的**那一帧**里跑一次，
 *     摊到平时可以忽略；但它是一段 0.5~5ms 的**突发**，
 *     如果录音回调对抖动敏感，把 kws_feed 挪到独立线程（见下面"接线"）。
 *
 *   ⚠ 这里**故意不用 double**：M33 没有双精度 FPU，double 是软实现
 *   （一次 ~几百周期），所以文件里所有常量都带 f 后缀、只用 float 版数学函数。
 *
 * 【阈值】
 *   默认 KWS_THRESHOLD_MILLI = 1800，单位是"每维每帧 RMS 距离 × 1000"，
 *   即 1.8 个 MFCC 单位。
 *   这个默认值是**算出来**的，不是拍的：拿同一套公式在合成信号上复核过一遍
 *   （两段低频噪声拼的假词 + 变换语速/音量/噪声；复核脚本是交接时的一次性
 *   验算，放在仓库外，不参与构建）：
 *     同一句、换录音/±25~40% 语速/音量 -8dB → 距离 588~837
 *     模板的帧顺序被打乱（值域不变、时间结构没了）→ 2278~2490
 *     整段白噪声 → 2985
 *   1800 卡在"同句上界 837"和"结构打乱下界 2278"之间（同句留 2.1 倍余量）。
 *   偏宽是故意的：现场第一次录完模板就得能跑通（宁可先敏感），
 *   误唤醒再靠上板实测的推荐值收紧。
 *   ⚠ 真实人声的类内差异比这个合成信号大，所以**第一次上板录完模板后，
 *   一定要跑 kws_selftest()**，按它打印的推荐值 kws_set_threshold() 覆盖。
 *   kws_set_threshold() 随时可改（不用重新编译），便于现场标定。
 *
 *   宿主 gcc 上的复测（2026-09-14，合成短语 + board 自带的 test_16k.wav）：
 *     同一段 → 0（特征逐点相同）
 *     同词变体（语速 +15%、音量 -8dB、换噪声）→ 658；模板插值拉伸 1.25 倍 → 620
 *     同词语速扫 -40%~+50% → 543~848（全命中）
 *     不同词（音节数/共振峰全换）→ 2449；模板帧序打乱 → 3068
 *     有边界的噪声段（1.2s 噪声 + 前后静音）→ 2828~2842，不命中
 *     真实 wav 里换一段 1.5s（不是同一句）→ 2564
 *     静音/全 0/±6 本底噪声 → 压根不起端点，不判
 *     3 秒白噪声（幅度 3000）→ 常起端点、尾静音永远不来，一直不判（不命中）
 *   即类内 620~660、类外 2450~3100，1800 落在中间偏保守的位置。
 *
 *   ⚠ 1800 的**真实margin 比上面看起来小**，两件事要说清楚（都是合成信号实测）：
 *     1) 同音节换顺序（同长、同频谱内容，只重排）→ 1806/2004，几乎贴着 1800；
 *        只调换相邻两个音节 → 904，**直接误命中**。
 *        也就是说"长度对得上、内容同源"的负例，DTW 区分度很弱。
 *     2) 反过来，只念整句的一部分（前半段/后半段）→ 根本没算距离：
 *        长度差超出 KWS_BAND_* 带宽，直接按"不是这句话"处理（返回 -1）。
 *        所以挡住"只说 openvela 不带称呼语"这类误唤醒的，主要是**长度门**，
 *        不是距离。要收紧就得靠多录几条模板 + 上板实测类内距离。
 *     → 想要区分度余量，可考虑把默认阈值收到 1100~1300（类内 660 / 最难负例 1806
 *       的几何中点是 ~1090）。默认值没改，改动留给上板标定决定。
 *
 *   ⚠ 上限：**别把阈值设过 9000**。距离被 DTW 的 DP 上限钉住，
 *   饱和值只由"模板点数+句子点数"决定：qn+tn=200 → 9690、120 → 12510。
 *   阈值设到 1 万以上 = 任何输入都命中（阈值失效）。kws_set_threshold()
 *   超过 9690 会打一行警告，但**不拒绝**（现场标定的人可能是故意的）。
 *
 * ============================================================================
 * 模板文件（持久化）
 * ============================================================================
 *   目录 /data/kws/，文件名 slot<N>.tpl，内容是 24 字节头 + int16 特征点。
 *   ⚠ /data 在本板是 tmpfs —— **重启就没了**。所以要长期保留只有"重启后
 *   自动补回来"这一条路，现在有两条来源：
 *     (a) 出厂模板：放进 ROMFS 的 /etc/assets/kws/slotN.tpl 随固件打包，
 *         开机时 kws_init() 自动把它补到 /data/kws（目标已存在则不覆盖，
 *         现场录的优先）—— 仓库里不放这个目录也完全正常，缺失时安静跳过；
 *     (b) 现场录：kws_enroll()（hw_test 的 `kws enroll <slot>` 是唯一入口）
 *         录一次就落盘，但**只在本次开机有效**；要让下一次开机也有，
 *         得照 (a) 把它放进 assets 里重新打包烧录。
 *   本模块只负责 /data/kws/ 这一份，落盘失败不算致命（见 kws_enroll 返回 1）。
 *   运行中模板变多/变少之后调 kws_template_load_all() 让内存里的模板跟上。
 *
 *   文件头（24 字节，见 kws_tpl_hdr_t）：
 *     magic 'KWST' / version / dim / frames / q / rate / sum / hop_ms
 *   载入时逐条核对：魔数、版本、特征口径(dim/q/rate/hop)、点数范围、
 *   以及负载的字节和校验和。**任何一条对不上就整条拒绝**，不做"尽力读"——
 *   读出一堆被当模板用的垃圾特征比"这个槽没有模板"危险得多。
 *   所以换特征口径（改 KWS_*_MFCC/Q/HOP 之类）时必须把 KWS_TPL_VERSION +1，
 *   旧文件会被版本检查明确挡住并打印日志，而不是悄悄按新口径解释。
 *
 *   落盘走的是**临时文件 + rename**（见 kws_template_save）：不会留下"头合法、
 *   内容是半截"的文件。注意覆盖旧模板时 NuttX 的 VFS 是先 unlink 再改名，
 *   不是原子替换；/data 是 tmpfs，掉电本来就整片丢，所以不为那个窗口额外
 *   兜底（见 kws_tpl_save 里的说明）。
 *
 * ============================================================================
 * 接线（父 agent 怎么喂帧）
 * ============================================================================
 *
 *   // 1) 起录音线程之前初始化（先补装出厂模板，再去 /data/kws 读模板）
 *   kws_init();
 *   printf("[KWS] 唤醒词模板 %d 条\n", kws_ready_count());
 *   // 录完模板后跑一次自检，按它打印的推荐值定阈值：
 *   // kws_selftest();  kws_set_threshold(推荐值); kws_set_vad_db(-40, -46);
 *
 *   // 1b) 录模板（有唤醒词录制交互时做一次；录完就是持久模板了）
 *   //     麦克风持有者录一段"前后带静音"的整句 PCM，然后：
 *   //
 *   //     rc = kws_enroll(pcm, n_samples, 0);   // slot0 =「你好，openvela」
 *   //     if (rc == 1)                          // 内存里有、盘上没写成功
 *   //       kws_template_save(0);               // /data 挂上了就重试落盘
 *   //     if (kws_slot_ready(0))                // 录成功没（hw_test 的 kws test 也用这个）
 *   //       kws_selftest();
 *   //
 *   //     ⚠ kws_enroll 会清流式状态，别在"正在听唤醒词"的中途调；
 *   //       录完记得 kws_reset() 再回去听。
 *
 *   // 2) 麦克风持有者的**录音数据回调**里喂（ai_audio.c:535 那个
 *   //    data_callback，或 robot_ui/ambient_listen.c 里自己 audio_in_read 的地方）：
 *   //
 *   //    唤醒词模块只认"文本事件"，它不认识状态机里的结构体（也就不能替
 *   //    父 agent 决定投给谁）。两种接法都行：
 *   //      a) 直接在录音线程里 sm_handle_event(ctx, SM_EVENT_WAKEUP);
 *   //         （ai_state_machine.h:129；sm_handle_event 只改状态机内部状态，
 *   //          不碰 LVGL，所以录音线程里调是安全的）
 *   //      b) 想要"录音线程只管喂、唤醒在别的线程处理"，就在回调里置一个
 *   //         全局标志 / 丢消息队列，让 ai_companion_main 的主循环去
 *   //         sm_handle_event —— 顺手也把 DTW 的毫秒级抖动从录音线程挪走。
 *   static void on_pcm(const int16_t *data, size_t frames, void *arg)
 *   {
 *     (void)arg;
 *     if (kws_feed(data, frames) == 1)      // frames 是**采样点个数**（int16 个数）
 *       {                                   // 不是字节数！单声道下就是采样数
 *         wakeup_flag = true;               // 命中：交给主循环去
 *       }                                   // sm_handle_event(SM_EVENT_WAKEUP)
 *   }
 *
 *   // 3) 把麦克风交给 ASR 之前、或再次开始听唤醒词之前，清一下运行时状态：
 *   kws_reset();
 *
 *   帧边界：**不用管**。kws_feed 内部自己攒 20ms 窗（10ms 跳），
 *   调用方给 320 点、给 160 点、给 1000 点、甚至给 1 点都对：
 *   凑不满一窗就留在内部缓冲里，下一次接着凑。
 *   ⚠ 千万不要自己按 160 的比例切好了再喂 —— 那样很容易把 320 的窗切成两半。
 *
 *   已知的体感代价（说清楚）：命中是在**尾静音超时(KWS_TAIL_MS=300ms)
 *   那一帧**报出来的，所以从"说完最后一个字"到 kws_feed 返回 1，
 *   固定有 ~300ms 延迟。命令词识别都这样（要确认你说完了才能整句对齐）。
 *
 * ============================================================================
 * 线程安全
 * ============================================================================
 *   没有锁：**只能有一个线程调用本模块**的接口（典型的就一个录音线程）。
 *   不要把 kws_feed 和 kws_enroll 放到两个线程里同时跑。
 ****************************************************************************/

