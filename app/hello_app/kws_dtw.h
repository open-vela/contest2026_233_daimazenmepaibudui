/* ---- 音频与特征参数（改了要同步 KWS_*_FEAT / 头注释里的量化数字）---- */

#define KWS_SAMPLE_RATE     16000               /* 采样率（固定，写入模板头校验） */
#define KWS_FRAME_MS        20                  /* 窗长 20ms */
#define KWS_HOP_MS          10                  /* 跳距 10ms（50% 重叠） */
#define KWS_FRAME_LEN       (KWS_SAMPLE_RATE * KWS_FRAME_MS / 1000)  /* 320 采样 */
#define KWS_HOP_LEN         (KWS_SAMPLE_RATE * KWS_HOP_MS / 1000)    /* 160 采样 */
#define KWS_FFT_LEN         512                 /* 320 点补零到 2 的幂 */
#define KWS_FFT_BITS        9                   /* log2(KWS_FFT_LEN) */
#define KWS_NUM_MEL         26                  /* Mel 三角滤波器个数 */
#define KWS_NUM_MFCC        13                  /* 特征维数 */
#define KWS_MFCC_Q          64                  /* 定点 Q6：值 = MFCC × 64 */
#define KWS_MFCC_MAX        4096                /* 定点削顶（Q6 → ±64 MFCC 单位） */
#define KWS_PREEMPH         0.97f               /* 预加重系数 */
#define KWS_C0_WEIGHT       0.5f                /* 第 0 维（dBFS 能量）权重，见文件头 */
#define KWS_DECIM           2                   /* 匹配用特征点 2:1 抽取 → 20ms 一个点 */

#define KWS_FEAT_MS         (KWS_HOP_MS * KWS_DECIM)   /* 一个特征点 = 20ms */

/* ---- 端点检测 / 句子长度 ---- */

#define KWS_MAX_FEAT        100                 /* 一句话最多 100 个特征点 = 2.0s */
#define KWS_PREROLL_FEAT    10                  /* 预滚环 10 个点 = 200ms */
#define KWS_MIN_FEAT        8                   /* 少于 8 个点(160ms)不判 */
#define KWS_TAIL_MS         300                 /* 尾静音超时 = 命中延迟的主要来源 */
#define KWS_COOLDOWN_MS     1000                /* 命中后冷却，防一次说话连报几次 */

/* 绝对地板（0.1dBFS 定点，例如 -420 = -42.0 dBFS）。
 * -40/-46 是按 robot_ui/ambient_listen.c 里实测的本底标定的：
 * 那儿的注释写"安静房间本底几十到一两百、正常说话几百到一千五"（平均幅度口径），
 * 折成 dBFS 就是本底约 -48~-45、说话约 -35~-25。
 * 实际判定还会叠加自适应本底（见 .c 里的 kws_vad_thresholds()）。 */

#define KWS_VAD_ON_DB10     (-400)              /* -40.0 dBFS */
#define KWS_VAD_OFF_DB10    (-460)              /* -46.0 dBFS */
#define KWS_VAD_MARGIN_DB10 60                  /* 相对本底：起 +6dB / 落 +3dB */
#define KWS_VAD_HYST_DB10   30

/* ---- DTW ---- */

/* Sakoe-Chiba 带宽 r = KWS_BAND_MIN + KWS_BAND_RATIO × max(模板长, 句子长)，
 * 判定条件是 |i - j| ≤ r（i/j 是模板/句子的特征点序号）。
 * 怎么定的：0.20 × 长度 + 6 个点，也就是"整句最多容许 20% 的语速漂移，
 * 再加 6 个点（120ms）的固定余量"。65 点的短语 → r = 19（±380ms）；
 * 100 点 → r = 26。再宽会把"不同词"也对上（区分度下降、格子数线性涨），
 * 再窄正常语速变化就会漏（尤其"你好"和"openvela"中间的停顿长短）。
 *
 * 实测（59 点模板、4 音节合成短语）：r = 17。
 *   同一个词、语速 -40%~+50% → 全都命中（距离 543~848）；
 *   -50%（快一倍）和 +60% → **直接返回 -1，等于"不是这句话"**，
 *   一点距离都不算。也就是说超出带宽不是"距离大"，是**硬拒绝**，
 *   kws_get_last_distance() 会看到 -1。
 *   这是设计上的取舍：长度差异大的东西压根不该进入打分区
 *   （挡"只说 openvela 不带称呼语"就靠这一条）。但它有代价：
 *   真人语速差异、或模板录得太短时，会在带宽上直接漏掉，
 *   而日志上只表现为"没命中"。真漏了就多录一条语速不同的模板。 */

#define KWS_BAND_RATIO      0.20f
#define KWS_BAND_MIN        6

/* ---- 模板 ---- */

#define KWS_MAX_TEMPLATES   4                   /* 模板槽个数（每条 2600 字节 RAM） */
#define KWS_DATA_DIR        "/data/kws"

/* ---- 阈值与返回码 ---- */

#define KWS_THRESHOLD_MILLI 1800                /* 默认阈值，见文件头"阈值"一节 */

#define KWS_ERR_RANGE       (-1)                /* slot / 参数越界 */
#define KWS_ERR_STATE       (-2)                /* 没初始化 / 没有可用模板 */

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/**
 * @brief  初始化：建表（窗/Mel/DCT/FFT 旋转因子）+ 补装出厂模板 + 读 /data/kws 模板
 * @return 0 成功（**没有模板也算成功**，用 kws_ready_count() 看有几条）；
 *         负值 = 参数/内部表异常
 *
 * 不碰音频设备、不起线程。必须在任何 kws_feed 之前调一次。
 *
 * 读模板之前会先把 ROMFS 的 /etc/assets/kws/slotN.tpl 补到 /data/kws
 * （/data 是 tmpfs，重启就空；没有素材就安静跳过，不影响启动）。
 * 所以"开机即用唤醒词"只要把录好的 .tpl 放进那个 assets 目录重新打包即可。
 */

int kws_init(void);

/**
 * @brief  喂一段 PCM（16k / 单声道 / s16le），流式识别
 * @param  pcm    PCM 数据（int16 采样）
 * @param  frames **采样点个数**（不是字节数）
 * @return 1 = 刚匹配到唤醒词；0 = 没匹配（绝大多数调用）；
 *         负值 = 出错（-EINVAL 参数非法 / -ENOSYS 没初始化）
 *
 * 最耗时的分支就是返回 1 的那一次：它内部跑完了 1~4 次 DTW
 * （每模板约 0.7ms @240MHz，见文件头）。其余调用只是一帧 MFCC（约 270us/10ms）。
 * 命中后自动进 KWS_COOLDOWN_MS 冷却并清运行时状态，不会连着返回 1。
 */

int kws_feed(const int16_t *pcm, size_t frames);

/**
 * @brief  把一段录音当模板存下来（槽 slot = 0..KWS_MAX_TEMPLATES-1）
 * @param  pcm    录音（16k/单声道/s16le），前后带一点静音最好
 * @param  frames 采样点个数
 * @param  slot   模板槽号
 * @return 0 = 存好且落盘成功；1 = 模板进 RAM 了但**写 /data/kws 失败**
 *         （/data 可能是 tmpfs 或没空间 —— 重启会丢，日志里有原因）；
 *         负值 = 失败：-EINVAL 太短/太安静/参数非法，-ENOSPC 有效语音超过
 *         KWS_MAX_FEAT(2.0s)，-ENOSYS 没初始化
 *
 * 走的是和 kws_feed 完全同一条特征流水线 + 同一个端点检测，
 * 保证"录模板"和"跑识别"的特征口径一致（这是 DTW 能不能用的前提）。
 * ⚠ 会清掉当前的流式状态（相当于 kws_reset()），
 *   别在"正在连续听唤醒词"的中途调它。
 */

int kws_enroll(const int16_t *pcm, size_t frames, int slot);

/**
 * @brief  设置判定阈值
 * @param  th 阈值，单位"每维每帧 RMS 距离 × 1000"（1800 = 1.8 MFCC 单位）
 *
 * 直接对阈值做上下限保护（200~20000），非法值忽略。
 * ⚠ 大于 9690（DTW 饱和距离的下限）时只是**警告**、仍然生效，
 *   但那个区间里阈值已经失效（任何输入都命中）—— 见文件头"阈值"一节。
 */

void kws_set_threshold(int th);

/**
 * @brief  读当前阈值（同上口径）
 */

int kws_get_threshold(void);

/**
 * @brief  自检：喂合成数据 + 模板自比对，打印实测数字
 * @return 0 = 全部通过；负值 = 有检查项失败（失败原因已经 printf 出来了）
 *
 * 具体做四件事（对应文件头"阈值"一节的标定需求）：
 *   1) 合成 1kHz 正弦跑一帧，检查 FFT 峰值落在 32 号 bin、Mel 峰值落在第 8 个
 *      滤波器 —— 表建错了、补零错了、Mel 映射错了都会在这里露出来；
 *   2) 拿模板 0 自己跟自己比（距离应≈0）、跟"时间拉伸 1.25 倍"的副本比
 *      （DTW 应该吸收掉，距离仍然很小）、跟"把模板自己的帧序打乱"的假句子比
 *      （值域同分布、只剩时间结构没了，距离应该明显大），
 *      并据此**打印推荐阈值**（打乱的帧序自校准量级，所以推荐值可直接用）；
 *   3) 有 2 条以上模板时打印互距离（用来发现两条模板其实是同一句话）；
 *   4) 实测一次 MFCC 帧耗时和一次 DTW 耗时（微秒），直接看板子上的真实开销。
 * 不动流式状态、不改模板，可以随时调（比如开机后打一次日志）。
 */

int kws_selftest(void);

/**
 * @brief  当前有几条可用模板（0 = 还没录过，kws_feed 永远不会返回 1）
 */

int kws_ready_count(void);

/**
 * @brief  清运行时流式状态：预滚环、待判句子、端点/冷却状态、自适应本底
 * @note   不清模板。把麦克风交给 ASR 之前/重新开始听之前调一次。
 */

void kws_reset(void);

/**
 * @brief  改端点检测的地板（dBFS，例如 kws_set_vad_db(-40, -46)）
 * @param  on_dbfs  起端点地板，0 = 保持默认
 * @param  off_dbfs 落端点地板（必须比 on 低），0 = 保持默认
 *
 * 现场标定入口：麦克风增益/房间本底变了、或发现"说话也不起端点"/
 * "环境音一直在起端点"，就调这两个值（自适应本底那部分不用管）。
 */

void kws_set_vad_db(int on_dbfs, int off_dbfs);

/**
 * @brief  改尾静音超时（毫秒，默认 KWS_TAIL_MS=300）
 *
 * 调小 → 唤醒更快但容易把句子切断；调大 → 稳但更迟钝。
 */

void kws_set_endpoint_ms(int tail_ms);

/**
 * @brief  最近一次判定的最小距离（同阈值的"×1000"口径）
 * @return 距离（×1000）；-1 = 还没有判定过，或那次判定因为长度差超带宽被跳过
 *
 * 给父 agent 打日志/现场看"差多少"用，不参与判定。
 */

int kws_get_last_distance(void);

/**
 * @brief  离线段距离：一整段录音到某条模板的距离（调试/标定用）
 * @param  pcm         录音（16k/单声道/s16le），前后带静音最好
 * @param  frames      采样点个数
 * @param  slot        模板槽号
 * @param  dist_milli  输出：距离 × 1000（同阈值口径）
 * @return 0 成功；负值 = 失败（-EINVAL：参数非法 / 有效语音太短 /
 *         长度差超出 DTW 带宽——最后这条等于"完全不像"，按不命中处理即可；
 *         -ENOSYS 没初始化）
 *
 * 内部复用喂帧 + 端点路径，同时**会清掉流式状态**（同 kws_enroll 的注意事项）。
 */

int kws_distance_pcm(const int16_t *pcm, size_t frames, int slot,
                     int *dist_milli);

/**
 * @brief  某条模板的特征点个数（一个点 20ms）
 * @return 点数；槽非法或空模板返回 0
 */

int kws_template_frames(int slot);

/* ---------------------------------------------------------------------------
 * 模板落盘 / 载入 / 就绪查询
 * ---------------------------------------------------------------------------
 * 三个都是**给外部调用者**（hw_test 的 `kws test`、开机流程）用的接口。
 * 内部实现是 static kws_tpl_save/kws_tpl_load，这里只是包一层参数校验和
 * 返回码翻译 —— 所以和 kws_enroll 的落盘是**同一份代码、同一个文件格式**。
 */

/**
 * @brief  该槽位现在有没有可用的模板（内存里的，载入的也算）
 * @return 1 = 有；0 = 没有或 slot 非法（不返回负值，方便直接当布尔用）
 *
 * hw_test 的 `kws test` 用它决定"这个槽能不能拿来比对"。
 */

int kws_slot_ready(int slot);

/**
 * @brief  把 4 个槽位都尝试从 /data/kws/slotN.tpl 载入
 * @return 成功载入的个数（0..KWS_MAX_TEMPLATES）；-ENOSYS = 没 kws_init
 *
 * 就是 kws_init() 内部走的那条路，单独暴露出来给"运行中重新载入模板"用
 * （例如父 agent 把 flash 里持久化的模板拷回 /data 之后再调一次）。
 * 载入会**覆盖**对应槽位的内存模板；文件不存在/坏了就把该槽位清成"没有"。
 *
 * 文件不存在是正常情况（本板 /data 是 tmpfs，开机就是空的 —— 除非固件里
 * 带了出厂模板，见 kws_init 的补装那一步），
 * 所以它只打一行汇总 INFO（"[KWS] 模板载入：N/4 条可用"），
 * 每个槽位的结果走 KWS_LOG（默认编掉）。真坏文件（魔数/版本/校验不过）
 * 由 kws_tpl_load 打自己的 ERROR 行 —— 那才是要看的东西。
 *
 * ⚠ 只动模板，不动流式状态；但载入的模板会被之后的 kws_feed 立刻用上。
 */

int kws_template_load_all(void);

/**
 * @brief  把内存里的某条模板原子地写进 /data/kws/slotN.tpl
 * @param  slot 模板槽号 0..KWS_MAX_TEMPLATES-1
 * @return 0 = 写成功；-EINVAL = slot 越界或该槽还没有模板；
 *         -EIO = 写盘失败（目录建不出来/打不开/写不全/改名失败，
 *         原因已经 printf 出来了）；-ENOSYS = 没 kws_init
 *
 * 什么时候需要单独调它：kws_enroll() 自己会落盘，所以正常流程用不到；
 * 它是给"模板已经在内存里、但 /data 是刚刚才挂上/掉过电"这种场景兜底的
 * （kws_enroll 返回 1 就表示"内存里有、盘上没写成功"，这时拿它重试即可）。
 *
 * **落盘的原子性**：先写同目录的 slotN.tpl.tmp，写完再 rename 成 slotN.tpl。
 * 这样就不会留下"长度对、内容是半截"的垃圾文件 —— 那种文件头是完整的，
 * 读回来会当合法模板用，比读不出来危险。
 * ⚠ rename 只在**目标不存在**时是一次原子的公开改名；覆盖旧模板时 NuttX 的
 * VFS 先 unlink 再 rename，中间有一刻 slotN.tpl 这个名字底下是空的。那个
 * 窗口里掉电会丢旧模板，但 /data 是 tmpfs，掉电本来就整片丢，不差这一下。
 */

int kws_template_save(int slot);

