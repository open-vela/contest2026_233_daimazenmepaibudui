/****************************************************************************
 * app/hello_app/mimo_location.h
 *
 * IP 定位：板子自己打一个免 key 的 HTTPS 接口，问"我现在大概在哪个城市"，
 * 结果拿给 mimo_chat() 写进 system prompt（用户问"我在哪""今天天气怎么样"
 * 这类问题时模型才答得上来）。
 *
 * 实现见 mimo_location.c。不用配任何密钥，但要联网：查不到一律返回负值，
 * 调用方（mimo_chat）在这种情况下一个字都不往 prompt 里写 —— 模型不知道，
 * 就不会编一个城市给用户。
 *
 ****************************************************************************/

#ifndef __APP_HELLO_APP_MIMO_LOCATION_H
#define __APP_HELLO_APP_MIMO_LOCATION_H

/****************************************************************************
 * Included Files
 ****************************************************************************/

#include <stddef.h>

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/****************************************************************************
 * Name: mimo_location_get
 *
 * Description:
 *   取"板子现在大概在哪个城市"。第一次调用会打网络（HTTPS GET，见
 *   mimo_location.c 的接口表），查到了就缓存（默认 6 小时），之后的调用直接
 *   从缓存返回、**不再联网**；失败也记一笔退避（默认 5 分钟），这段时间里
 *   直接返回失败 —— 免得每次对话都卡在同一个连不通的接口上。
 *
 *   这是**同步阻塞**接口（内部一次 TLS 请求，慢起来要等 socket 的连接 /
 *   读超时），只能在非 LVGL 线程里调；mimo_chat() 本来就跑在语音工作线程里，
 *   直接调没问题。
 *
 * Input Parameters:
 *   city - 输出：城市名（UTF-8）。接口给的可能是英文或拼音（例如 Hangzhou），
 *          调用方把它喂给模型时自己说明一下就行；失败时置成空串；
 *   cap  - city 的字节数（建议 64，最少 16）；
 *   lat  - 输出：纬度。允许传 NULL（不需要就别要）；
 *   lon  - 输出：经度。允许传 NULL。
 *
 * Returned Value:
 *   OK    - city 里是城市名，同时 lat / lon 也有效；
 *   <0    - 负 errno：
 *           -ENOENT 接口通了但没查出城市，或者正处在失败退避里；
 *           -EIO    网络层失败（DNS / 连接 / TLS / HTTP 非 200）；
 *           -ENOMEM 内存不够；-EINVAL 参数不对。
 *           **拿到负值就什么都别提**，不要写"位置未知"之类的话。
 *
 ****************************************************************************/

int mimo_location_get(char *city, size_t cap, double *lat, double *lon);

#endif /* __APP_HELLO_APP_MIMO_LOCATION_H */
