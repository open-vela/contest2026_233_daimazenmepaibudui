/****************************************************************************
 * app/hello_app/voice_emerg.h
 *
 * 语音急救报警：老人喊「救命」「着火了」这类话（**不需要唤醒词**）→
 * 响铃 → 10 秒内说「没事」就停，否则 Bark 通知家人。
 *
 * ============================================================================
 * 为什么响铃不走 sf32lb52_alarm.c
 * ============================================================================
 * 那个模块是 `open(AUDIOIOC_STOP/close` 直接怼设备的，**没有任何人补"还麦"**。
 * 而本板半双工：它每轮 close 发的那个 AUDIOIOC_STOP 会把 hello_app 正在跑的
 * 录音 read 打成 EOF（驱动 session_gen++ + post，见 sf32lb52_audio.c 的 stop
 * 段）。录音线程按"被别人抢走"收尾（stolen → 只 close 不发 STOP），
 * 之后靠监听守护重开 —— 而守护的节奏是 5 秒一次。
 *
 * 于是「响 1.2 秒 / 听 0.6 秒」里那 0.6 秒根本听不见：麦还没回来。
 * 偷听窗 = 0，10 秒确认就变成"永远听不到没事"，直接退化成 10 秒后必然报警。
 *
 * 换成 ai_audio.c 的 audio_play_start() 就没有这个问题：那条路走
 * 「半双工让路 → 播完自动还麦」（见 ai_audio.h 的 record_hold / 还麦注释），
 * 播完麦是**立刻**回来的，不是等守护。而且它用的是 hello_app 自己那份
 * g_audio_ctx —— ai_audio.h:312 记着的那次真机事故（2026-10-29 报警按钮
 * 一按，录音 28 次「异常中断」）正是"出声走别的 ctx、守护看不见"造成的，
 * 这里天然避开。
 *
 * ============================================================================
 * 为什么 Bark 必须另起线程
 * ============================================================================
 * push_send_alarm() 是一次 HTTPS 往返，本板实测约 5 秒。在工作线程里同步调它，
 * 这 5 秒铃就不响了 —— 直接违反"响铃不能中断"。所以推送单独丢一个 detached
 * 线程去发，铃该响照响。
 *
 * ============================================================================
 * 时间参数（都是宏，可调）
 * ============================================================================
 *   VOICE_EMERG_CONFIRM_MS   10000   确认窗口：这之内说「没事」就取消
 *   VOICE_EMERG_RING_MS       1200   响
 *   VOICE_EMERG_LISTEN_MS     2800   听（Bark 发出**之后**的持续响铃期）
 *   VOICE_EMERG_LISTEN_CONFIRM_MS
 *                             2800   听（10 秒确认期内，见下面那段）
 *   VOICE_EMERG_RENOTIFY_MS  30000   Bark 重发间隔
 *   VOICE_EMERG_AUTOSTOP_MS 180000   到点自动收摊（用户 2026-11-01 拍板 3 分钟）
 *
 * ⚠ 板子半双工决定了说话时麦是聋的，原来 600/1800 = 1/3 的听音占空比
 *   连「没事」都经常收不全（2026-11-01 真机：喊了 3 次，0 次被语音停掉）。
 *   而「没事」两个字约 0.5 秒，要整段落进 0.6 秒窗口才认得出 ——
 *   概率并不高。这是本方案最大的不确定点，2026-10-31 两处对策一起上：
 *     ① 确认期内把"听"放宽到 1.6 秒（VOICE_EMERG_LISTEN_CONFIRM_MS）；
 *     ② 确认窗内把 VAD 的**两道**门都压到 200 ms（voice_emerg.c 的
 *        VE_VAD_MIN_MS / VE_VAD_SIL_MS）—— 静音判停那道门原来 1000 ms，
 *        而它要攒的是"实际收到的"静音帧，铃一响就冻结，攒满得跨 3 个偷听窗，
 *        再加一趟 ASR，稳超 10 秒，Bark 一定抢在「没事」前面发出去。
 *   验收判据写死：**10 次里 ≥ 8 次能被「没事」停掉**。
 ****************************************************************************/

#ifndef __APP_HELLO_APP_VOICE_EMERG_H
#define __APP_HELLO_APP_VOICE_EMERG_H

#include <stdbool.h>
#include <stdint.h>

#include "ai_audio.h"

/****************************************************************************
 * 时间参数
 ****************************************************************************/

#ifndef VOICE_EMERG_CONFIRM_MS
#define VOICE_EMERG_CONFIRM_MS    10000
#endif

#ifndef VOICE_EMERG_RING_MS
#define VOICE_EMERG_RING_MS       1200
#endif

/* 2026-11-01 用户要求「3 分钟报警 + 随时能说没事」之后从 600 提到 1200：
 * 铃 1.2s / 听 1.2s，一半时间在听。铃仍然是重复的高低音，不会变成"一直不响"。 */

#ifndef VOICE_EMERG_LISTEN_MS
#define VOICE_EMERG_LISTEN_MS     3600
#endif

/* ★ 确认窗口（10 秒）内的"听"单独给长一点，2026-10-31。
 *
 *   600 ms 那个数是按"持续响铃时顺带偷听"定的，用在**确认期**太苛刻：
 *   麦有 2/3 的时间是聋的，老人一句「没事」约 0.5 秒，整段落进窗口的概率
 *   只有三分之一 —— 而确认期只有一次机会，落空就是 Bark 打到家人手机上
 *   （判据⑥ 实测 0/10 就是这么来的）。
 *
 *   所以**分两段**：
 *     · 确认期（还没发 Bark）：响 1.2 / 听 2.8 —— 听的时间占 70%，
 *       一轮 4 秒、10 秒里能响 2~3 声，警报照样是"重复的"；
 *       听窗必须够长：VAD 说"这段说完了"还要 200 ms 实际静音，截短了
 *       「没事」会被下一声铃直接切断（2026-11-01 实测听窗 2.0 秒时，
 *       门控刚开麦、话还没收完铃就响了）。
 *     · 发完 Bark 之后：响 1.2 / 听 1.2 —— 一半时间在听，3 分钟里
 *       一直留着说「没事」的机会，同时铃声仍然反复。
 *
 *   要退回更"密"的铃，把这两个宏往小的改就行，一行的事。 */

#ifndef VOICE_EMERG_LISTEN_CONFIRM_MS
#define VOICE_EMERG_LISTEN_CONFIRM_MS 3600
#endif

#ifndef VOICE_EMERG_RENOTIFY_MS
#define VOICE_EMERG_RENOTIFY_MS   30000
#endif

/* 2026-11-01 用户拍板：报警总时长从 60 秒提到 3 分钟。
 * 节奏不变：10 秒确认期到就发 Bark，之后每 30 秒重发一次，3 分钟到点自动收摊
 * （也就是 10/40/70/100/130/160 秒各一发，共 6 发）。 */

#ifndef VOICE_EMERG_AUTOSTOP_MS
#define VOICE_EMERG_AUTOSTOP_MS   180000
#endif

/****************************************************************************
 * 统一报警路径总开关（2026-10-31）
 *
 * 用户原话：「ai 报警和自主本地检测到摔倒和异常声音报警是**一个路径**，
 * 都要按我说的来」。开 = 三条报警入口（语音急救词 / AI 工具 report_emergency /
 * 本地摔倒与异常声）全走本模块这一份实现：
 *
 *     响铃不许断 → 10 秒内说「没事」或点屏幕「我没事，取消」→ 不通知家人
 *     → 否则 Bark 通知家人 → 持续响 + 30 秒重发 → 期间说「没事」仍可停
 *     → 60 秒自停
 *
 * 关 = 退回旧行为（本地那条走 20 秒追问，超时按「不用了」停铃、不报警）。
 * 出问题一行改回 0 就是回退开关。
 * 放在头文件里是因为三处都要看它：hello_app 的两个入口、robot_ui 的收口。
 ****************************************************************************/

#ifndef ALARM_UNIFY_VOICE_EMERG
#define ALARM_UNIFY_VOICE_EMERG   1
#endif

/****************************************************************************
 * Public Types
 ****************************************************************************/

/* 报警确认流程走到哪一步了 */

enum voice_emerg_phase_e
{
  VOICE_EMERG_IDLE = 0,      /* 没在报警 */
  VOICE_EMERG_CONFIRM,       /* 响铃中，等 10 秒确认 */
  VOICE_EMERG_NOTIFIED,      /* 已经 Bark 通知家人，持续响 + 30 秒重发 */
  VOICE_EMERG_CANCELLED,     /* 老人说了「没事」，已停 */
  VOICE_EMERG_EXPIRED,       /* 60 秒到点自动收摊 */
};

/****************************************************************************
 * 阶段回调（给界面用）
 *
 * 2026-10-31 加。统一报警路径要求**屏幕跟着状态走**：确认期说「10 秒内说
 * 没事或点按钮取消」，Bark 发出去之后要说「已通知家人，30 秒后重发」，
 * 停了要把红页撤掉。界面在 LVGL 线程，本模块在工作线程 —— 不能直接碰控件，
 * 所以只回调一个函数，投递到哪条线程由调用方自己决定。
 *
 * 回调在**工作线程**里被调，禁止在里面做阻塞动作（网络/睡眠/等锁）。
 ****************************************************************************/

typedef void (*voice_emerg_hook_t)(enum voice_emerg_phase_e phase,
                                   const char *reason, void *arg);

/****************************************************************************
 * Public Function Prototypes
 ****************************************************************************/

/****************************************************************************
 * Name: voice_emerg_init
 *
 * Description:
 *   初始化语音急救模块：生成铃声音调、起工作线程。
 *   **需要 hello_app 那份 audio_context_t**（响铃走它的 audio_play_start，
 *   才有"播完还麦"；传 NULL 就是没接音频，只跑状态机不出声）。
 *
 * Returned Value:
 *   0 成功；负值失败。
 *
 ****************************************************************************/

int voice_emerg_init(audio_context_t *ctx);

/****************************************************************************
 * Name: voice_emerg_trigger
 *
 * Description:
 *   触发语音急救报警。**非阻塞**：立刻返回，响铃/计时/推送都在工作线程里做。
 *
 *   已经在报警中时**不重新计时**（只记一笔日志）：否则来一句假的「救命」
 *   就能把 10 秒确认窗口无限往后推，Bark 永远发不出去。
 *
 * Input Parameters:
 *   reason - 短标识，如 "voice_sos" / "sos_button"
 *   text   - 触发这句话（给人看，可 NULL）
 *
 ****************************************************************************/

void voice_emerg_trigger(const char *reason, const char *text);

/****************************************************************************
 * Name: voice_emerg_is_active
 *
 * Description:
 *   现在是不是正在语音急救报警（响铃或已通知持续响）。
 *   会话闸门、正常对话都要看它：报警期间不该再去送大模型。
 *
 ****************************************************************************/

bool voice_emerg_is_active(void);

/****************************************************************************
 * Name: voice_emerg_phase
 *
 * Description:
 *   读当前阶段，给诊断快照 / 串口日志用。
 *
 ****************************************************************************/

enum voice_emerg_phase_e voice_emerg_phase(void);

/****************************************************************************
 * Name: voice_emerg_on_text
 *
 * Description:
 *   **每一段 ASR 识别结果都要喂进来**（不管会话闸门锁没锁、不管是不是
 *   在报警）。它只认「没事」「我没事」「不用了」（用户拍板的窄口径），
 *   认出就把报警停掉。
 *
 *   ⚠ 别的什么都不做 —— 尤其**不许**因为说了别的话就停铃。
 *     "响铃不能中断"是硬要求，只有「没事」和到点能停它。
 *
 *   ⚠⚠ 调用方要**先**确认这句话不是急救词，再调本函数。
 *     否则「我没事，就是胸口疼」里的「没事」会把刚起的报警停掉 ——
 *     而那句恰恰是真急救。判定顺序和 ask_classify() 同一个道理：
 *     **急救在前、安抚在后**。
 *
 ****************************************************************************/

void voice_emerg_on_text(const char *text);

/****************************************************************************
 * Name: voice_emerg_cancel
 *
 * Description:
 *   **取消报警**（和说「没事」走同一条路）。给屏幕那个「我没事，取消」按钮用
 *   —— 用户拍板过：「点按钮」和「说没事」必须逐字一致。
 *
 *   什么阶段调都安全：不在报警中就只记一行日志。
 *
 * Input Parameters:
 *   src - 谁取消的（"屏幕按钮" / "语音「没事」" / ...），只进日志。
 *
 ****************************************************************************/

void voice_emerg_cancel(const char *src);

/****************************************************************************
 * Name: voice_emerg_confirm_left_ms
 *
 * Description:
 *   10 秒确认窗还剩多少毫秒（给屏幕上的倒计时用）。
 *   不在确认期返回 0。
 *
 ****************************************************************************/

unsigned voice_emerg_confirm_left_ms(void);

/**
 * @brief  这次报警已经持续了多少毫秒（不在报警返回 0）。
 *
 * 给主循环的"3 分钟兜底"用：`voice_emerg` 自己的到点检查只在工作线程的
 * 听窗里跑，工作线程万一卡在某一轮里就永远不会到点；主循环 100ms 一拍，
 * 到 180 秒无条件 `voice_emerg_cancel()`，铃和页面都能收。
 */

unsigned voice_emerg_elapsed_ms(void);

/****************************************************************************
 * Name: voice_emerg_set_hook
 *
 * Description:
 *   登记阶段回调（见上面 voice_emerg_hook_t 那段）。传 NULL 卸掉。
 *
 ****************************************************************************/

void voice_emerg_set_hook(voice_emerg_hook_t cb, void *arg);

#endif /* __APP_HELLO_APP_VOICE_EMERG_H */
